"""Author organic vine meshes in Blender; export smooth UV geometry for mobile runtime.
No humanoid or weapon geometry is generated. Material images are generated by the runtime PBR baker.
"""
import bpy, math, json, sys
from pathlib import Path
from mathutils import Vector
root=Path(__file__).resolve().parents[2]
high_poly='--high-poly' in sys.argv
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
def build(roots):
 vertices=[];uv=[];faces=[];along=[];sides=[];segments=1000 if high_poly and not roots else 160;radial=100 if high_poly and not roots else 20
 def center(t,branch):
  phase=branch*2.399963;angle=phase+t*(1.1+.13*branch)+.19*math.sin(t*11+branch)
  radius=t*1.55 if roots else .57+.12*math.sin(t*5+phase)+.08*math.sin(t*13+phase)
  return Vector((math.cos(angle)*radius,.035+math.sin(t*math.pi)*.11 if roots else t*2.4,math.sin(angle)*radius))
 for branch in range(5):
  for j in range(segments+1):
   t=j/segments;c=center(t,branch);tangent=(center(t+.001,branch)-center(t-.001,branch)).normalized()
   normal=tangent.cross(Vector((0,0,1))).normalized();binormal=tangent.cross(normal).normalized()
   width=(.065 if roots else .135)*pow(1-t,.7)+.006
   for k in range(radial+1):
    angle=k/radial*math.tau;knot=1+.12*math.sin(t*48+branch)+.07*math.sin(angle*5+t*29)
    p=c+normal*(math.cos(angle)*width*knot)+binormal*(math.sin(angle)*width*knot)
    vertices.append(tuple(p));uv.append((k/radial,t*7));along.append(t);sides.append(1 if math.cos(branch*2.399963) >= 0 else -1)
    if j<segments and k<radial:
     i=(branch*(segments+1)+j)*(radial+1)+k;faces.extend([(i,i+1,i+radial+1),(i+1,i+radial+2,i+radial+1)])
 mesh=bpy.data.meshes.new('OrganicRoot' if roots else 'GiantSpiritVines');mesh.from_pydata(vertices,[],faces);mesh.update()
 obj=bpy.data.objects.new(mesh.name,mesh);bpy.context.collection.objects.link(obj)
 layer=mesh.uv_layers.new(name='BarkUV')
 for poly in mesh.polygons:
  poly.use_smooth=True
  for li in poly.loop_indices:layer.data[li].uv=uv[mesh.loops[li].vertex_index]
 return {'side':sides,'position':[round(v,5) for p in vertices for v in p], 'normal':[round(v,5) for p in mesh.vertices for v in p.normal], 'uv':[round(v,5) for p in uv for v in p], 'along':[round(v,5) for v in along], 'index':[v for p in faces for v in p]}
data={'vines':build(False),'roots':build(True),'source':'Blender smooth-shaded organic tubes; 160 longitudinal / 20 radial segments, five irregular tapered stems; UV bark repeat seven times.'}
if high_poly:
 folder=root/'.local/manual-assets';folder.mkdir(parents=True,exist_ok=True)
 material=bpy.data.materials.new('OrganicBark_PBR');material.use_nodes=True
 nodes=material.node_tree.nodes;links=material.node_tree.links;surface=nodes.get('Principled BSDF')
 surface.inputs['Roughness'].default_value=.88
 noise=nodes.new('ShaderNodeTexNoise');noise.inputs['Scale'].default_value=38;noise.inputs['Detail'].default_value=5
 coord=nodes.new('ShaderNodeTexCoord');mapping=nodes.new('ShaderNodeVectorMath');mapping.operation='MULTIPLY';mapping.inputs[1].default_value=(5,.35,5)
 links.new(coord.outputs['Generated'],mapping.inputs[0]);links.new(mapping.outputs['Vector'],noise.inputs['Vector'])
 ramp=nodes.new('ShaderNodeValToRGB');ramp.color_ramp.elements[0].color=(.035,.027,.009,1);ramp.color_ramp.elements[1].color=(.20,.23,.065,1)
 links.new(noise.outputs['Fac'],ramp.inputs[0]);links.new(ramp.outputs['Color'],surface.inputs['Base Color'])
 bump=nodes.new('ShaderNodeBump');bump.inputs['Strength'].default_value=.35;bump.inputs['Distance'].default_value=.025
 links.new(noise.outputs['Fac'],bump.inputs['Height']);links.new(bump.outputs['Normal'],surface.inputs['Normal'])
 for obj in bpy.context.scene.objects:
  if obj.type=='MESH':obj.data.materials.append(material)
 bpy.ops.wm.save_as_mainfile(filepath=str(folder/'h01-organic-vines-high.blend'))
 report={'sourceTriangles':len(data['vines']['index'])//3,'rootTriangles':len(data['roots']['index'])//3,'runtimeVineTriangles':32000,'runtimeRootTriangles':32000,'highPolySource':'.local/manual-assets/h01-organic-vines-high.blend','highPolyShipped':False,'uv':'BarkUV','smoothShading':True,'runtimeMaps':['albedo 1024','normal 1024','roughness 1024'],'lossyReduction':True}
 (root/'docs/manual-assets/h01-entrance/vine-authoring.json').write_text(json.dumps(report,indent=2))
else:
 (root/'tools/manual-assets/generated/h01-organic-vines.json').write_text(json.dumps(data,separators=(',',':')))
print('Exported',len(data['vines']['index'])//3,'vine triangles')
