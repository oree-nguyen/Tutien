import fs from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const models = [
  ["H01", "assets/rigged/H01-C0-robe-panels-diagnostic.glb"],
  ["H02", "assets/rigged/H02-C0-rigged.glb"],
];
const generatedFiles = ["H01.glb", "H02.glb", "H01-held.json", "manifest.json"];

export async function copyRigReview({
  root = process.cwd(),
  enabled = process.env.HG_INCLUDE_RIG_REVIEW === "1",
} = {}) {
  const directory = join(root, "public/models/rig-review");
  try {
    if ((await fs.lstat(directory)).isSymbolicLink())
      throw Error("Refusing to modify symlinked rig-review directory: " + directory);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (!enabled) {
    let removedBytes = 0;
    // Own only these generated copies. Keep unknown files and subdirectories.
    for (const name of generatedFiles) {
      const target = join(directory, name);
      try {
        const entry = await fs.lstat(target);
        if (entry.isDirectory())
          throw Error("Refusing to remove a directory at generated file: " + target);
        removedBytes += entry.size;
        await fs.unlink(target);
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
    }
    return { enabled: false, removedBytes };
  }

  await fs.mkdir(directory, { recursive: true });
  for (const name of generatedFiles) {
    try {
      const entry = await fs.lstat(join(directory, name));
      if (!entry.isFile())
        throw Error("Refusing to overwrite non-file review copy: " + join(directory, name));
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  const entries = [];
  for (const [hero, source] of models) {
    const bytes = await fs.readFile(join(root, source));
    if (bytes.subarray(0, 4).toString() !== "glTF")
      throw Error("Missing LFS asset: " + source);
    const hash = createHash("sha256").update(bytes).digest("hex"),
      target = join(directory, hero + ".glb");
    let same = false;
    try {
      same =
        createHash("sha256")
          .update(await fs.readFile(target))
          .digest("hex") === hash;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (!same) await fs.writeFile(target, bytes);
    entries.push({
      hero,
      file: hero + ".glb",
      sha256: hash,
      bytes: bytes.length,
      status: "diagnostic-not-approved",
    });
  }
  await fs.copyFile(
    join(root, "docs/anim-report/harmonic-held/H01-reference-idle-solve.json"),
    join(directory, "H01-held.json"),
  );
  await fs.writeFile(
    join(directory, "manifest.json"),
    JSON.stringify({ version: 1, assets: entries }, null, 2) + "\n",
  );
  return {
    enabled: true,
    modelBytes: entries.reduce((sum, entry) => sum + entry.bytes, 0),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await copyRigReview();
  console.log(
    result.enabled
      ? `Opt-in rig review ready: ${result.modelBytes} model bytes copied unchanged.`
      : `Rig review excluded (set HG_INCLUDE_RIG_REVIEW=1 to include); removed ${result.removedBytes} stale generated bytes.`,
  );
}
