import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {createServer} from 'vite';
import {chromium} from 'playwright-core';
const executable=process.env.TOKTX??'/workspace/ktx-tools/KTX-Software-4.4.2-Linux-x86_64/bin/toktx';
const version=spawnSync(executable,['--version'],{encoding:'utf8'});if(version.status!==0)throw Error('toktx unavailable: '+executable);
const folder='public/art/character-baked',temporary=await fs.mkdtemp(path.join(os.tmpdir(),'hg-character-bake-'));
await fs.mkdir(folder,{recursive:true});
const server=await createServer({server:{host:'127.0.0.1',port:5186,strictPort:true}});await server.listen();
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
try{
 const page=await browser.newPage();await page.route('**/__bake.html',r=>r.fulfill({contentType:'text/html',body:'<html><body>Build-time texture baking</body></html>'}));await page.goto('http://127.0.0.1:5186/__bake.html');
 const entries={};let bytes=0;
 for(const detail of ['low','medium'])for(let hero=0;hero<12;hero++){
  const result=await page.evaluate(async({hero,detail})=>{
   const {HERO_APPEARANCE}=await import('/src/hero-anatomy.js');const {characterPBR,HERO_BROCADE_PATTERNS}=await import('/src/character-pbr.js');const THREE=await import('/node_modules/three/build/three.module.js');const c=HERO_APPEARANCE[hero];
   const outer=new THREE.Color(c.outer).offsetHSL(0,0,0).getHex();
   const maps=characterPBR.generateSilkBrocadeTexture(outer,new THREE.Color(outer).lerp(new THREE.Color(c.inner),.3).getHex(),c.gold,HERO_BROCADE_PATTERNS[hero],{detail});
   return {key:maps.albedo.userData.pbrKey,size:maps.size,images:Object.fromEntries(['albedo','normal','roughness','metalness','emissive'].map(k=>[k,maps[k].image.toDataURL('image/png')]))};
  },{hero,detail});
  const channels={};
  for(const [channel,uri] of Object.entries(result.images)){
   const name=`h${String(hero+1).padStart(2,'0')}-${detail}-${channel}`,png=folder+'/'+name+'.png',ktx=folder+'/'+name+'.ktx2';
   const input=Buffer.from(uri.split(',')[1],'base64');await fs.writeFile(png,input);
   const color=['albedo','emissive'].includes(channel),args=['--t2','--encode',color?'etc1s':'uastc','--genmipmap','--assign_oetf',color?'srgb':'linear','--assign_primaries','bt709','--lower_left_maps_to_s0t0','--threads','2'];
   if(color)args.push('--qlevel','255','--clevel','2');else args.push('--uastc_quality','2','--zcmp','18');
   const run=spawnSync(executable,[...args,ktx,png],{encoding:'utf8'});if(run.status!==0)throw Error(name+': '+run.stderr);
   const encoded=await fs.readFile(ktx);bytes+=encoded.length;channels[channel]={png:'/art/character-baked/'+name+'.png',ktx2:'/art/character-baked/'+name+'.ktx2',sha256:createHash('sha256').update(encoded).digest('hex'),bytes:encoded.length,encoding:color?'ETC1S':'UASTC'};
  }
  entries[hero+':'+detail]={key:result.key,size:result.size,channels};console.log('Baked fixed preset',hero+1,detail,result.size);
 }
 const algorithm=createHash('sha256').update(await fs.readFile('src/character-pbr.js')).digest('hex');
 await fs.writeFile('src/baked-character-assets.js','// Generated by scripts/bake-character-pbr.mjs; fixed default-costume palettes.\nexport const bakedCharacterAssets='+JSON.stringify(entries,null,2)+';\n');
 await fs.writeFile(folder+'/provenance.json',JSON.stringify({tool:version.stdout.trim(),algorithm,sets:Object.keys(entries).length,textures:Object.keys(entries).length*5,bytes,orientation:'lower-left; source CanvasTexture flipY=true',unchangedDimensions:{low:64,medium:256}},null,2)+'\n');
 console.log(JSON.stringify({sets:Object.keys(entries).length,textures:Object.keys(entries).length*5,bytes}));
}finally{await browser.close();await server.close();await fs.rm(temporary,{recursive:true,force:true});}
